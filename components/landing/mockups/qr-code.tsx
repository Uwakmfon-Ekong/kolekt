/* A believable-looking QR pattern (decorative only, it doesn't scan). */
const PATTERN = [
  "1111111010110101111111",
  "1000001011010001000001",
  "1011101001101101011101",
  "1011101010011001011101",
  "1011101011100101011101",
  "1000001001011001000001",
  "1111111010101011111111",
  "0000000011010100000000",
  "1101011100101101101011",
  "0110100011010010110100",
  "1011011101101011010110",
  "0100110010110100101101",
  "1101001101011011010010",
  "0000000010110101101011",
  "1111111001011010110101",
  "1000001011101011001010",
  "1011101010010101101101",
  "1011101001101010110110",
  "1011101011010101011010",
  "1000001010101101101101",
  "1111111011010110110110",
];

export function QrCode({ className = "h-28 w-28" }: { className?: string }) {
  return (
    <svg viewBox="0 0 22 21" className={className} shapeRendering="crispEdges" aria-hidden>
      {PATTERN.flatMap((row, y) =>
        [...row].map((cell, x) =>
          cell === "1" ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="#1A1028" /> : null,
        ),
      )}
    </svg>
  );
}
